//! `tui` —— 交互式终端界面（**规划中：本模块目前只有说明，没有实现**）
//!
//! 目标形态：`virlen-cli chat`（或多轮 `run`）——在终端里跟 Agent 循环对话，
//! 与桌面端共用同一份 `virlen.db`（会话 / 消息 / 配置），因此可以在 CLI 里续跑
//! 桌面端正在进行的会话。
//!
//! ## 为什么放在本 crate（而不是 core 或 bin）
//!
//! 三 crate 的分工是「core / cli / tauri」：core **零 `tauri::` 且不含入口**，
//! `virlen-app` 是唯一 Tauri 侧。终端 UI 属于「入口层」，因此住在这里；
//! bin（`src/main.rs`）**无法被单测引用**，所以实现必须在本 lib 内、bin 只转发。
//!
//! ## 已确定的部分（写在这里以免后续重新论证）
//!
//! - **不放 core**：TUI 需要终端库（`ratatui` / `crossterm` 之类），core 的边界是
//!   「引擎 + 持久化」，不该被 UI 依赖污染；CLI 侧加的依赖也不会进 GUI 二进制。
//! - **复用既有实现**：非交互路径（[`crate::run`]）已经把「装配资源 → 驱动引擎 →
//!   渲染事件 → 应答交互」跑通，TUI 应当复用其中的装配（`build_resources`）与
//!   事件渲染纯函数（`render_event`），只替换「输入循环」与「输出呈现」两处。
//!
//! ## 尚未拍板的取舍（动手前需要确认）
//!
//! 1. **行模式 REPL 还是全屏 TUI**：行模式（`rustyline`）改动小、能直接复用现有事件
//!    渲染，覆盖「多轮 + 工具审批内联提示」；全屏（`ratatui`）面板更接近桌面端，
//!    但流式渲染与审批要重写。
//! 2. **交互应答异步化**：现在 `ask_user` 是**同步阻塞读 stdin**（见 `crate::run`），
//!    与输入循环抢同一个 stdin，必须先改成「事件 → UI 层应答」的通道。
//! 3. **Ctrl+C 取消当前 run**：需要把 `AgentEngine::cancel` 接到信号上（一次性 `run`
//!    不需要，长驻 TUI 需要）。
//!
//! ## 依赖缺口（与桌面端相比，CLI 目前缺的能力）
//!
//! - `compressContext` / `generateTitle` 未原生化（长会话会撞上下文上限）；
//! - 费用展示需要把价目表（前端 `src/domain/pricing`）移植进 Rust；
//! - 路径白 / 黑名单、技能启用状态仍在桌面端 localStorage（见 `docs/AGENTS.md` §11.16）。
